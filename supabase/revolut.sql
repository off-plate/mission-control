-- Revolut (2026-11-07): his CZK account statement, read-only inside Mission Control.
-- The Revolut page and the mc-mcp connector only ever SELECT. There is no insert,
-- update or delete policy, so no signed-in session (and no model talking through
-- the connector) can change a row. The revolut-ingest function writes with the
-- service role, guarded by its own secret. Idempotent: safe to run again.

create table if not exists mc_revolut_tx (
  id          text primary key,                 -- hash of product, start, description, amount, type, nth repeat
  owner       uuid not null default auth.uid() references auth.users (id) on delete cascade,
  product     text not null,                    -- Current, Savings, Deposit (the statement's own names)
  type        text not null default '',
  started     timestamp not null,               -- Prague wall-clock time, as the statement prints it
  completed   timestamp,
  day         date generated always as (started::date) stored,
  description text not null default '',
  amount      numeric(14, 2) not null,
  fee         numeric(14, 2) not null default 0,
  currency    text not null default 'CZK',
  state       text not null default '',
  balance     numeric(14, 2),                   -- the pocket's running balance after this row; null while pending
  seq         int not null default 0,           -- statement order, breaks ties inside one second
  category    text not null default 'uncategorised',
  internal    boolean not null default false,   -- a move between his own pockets, not income or spending
  updated_at  timestamptz not null default now()
);

create index if not exists mc_revolut_tx_owner_started on mc_revolut_tx (owner, started desc, seq desc);
create index if not exists mc_revolut_tx_owner_day on mc_revolut_tx (owner, internal, day);

-- One row per owner: when the last sync ran and what it saw.
create table if not exists mc_revolut_sync (
  owner             uuid primary key default auth.uid() references auth.users (id) on delete cascade,
  synced_at         timestamptz not null default now(),
  rows_total        int not null default 0,
  rows_changed      int not null default 0,
  range_from        date,
  range_to          date,
  current_displayed numeric(14, 2)                -- the figure the Revolut home screen showed, pending included
);

-- His categorisation rules: first match by prio wins. Rows live in the database, not in this repo.
create table if not exists mc_revolut_rules (
  id        bigint generated by default as identity primary key,
  owner     uuid not null default auth.uid() references auth.users (id) on delete cascade,
  pattern   text not null,                        -- case-insensitive regex against the description
  category  text not null,
  internal  boolean not null default false,
  prio      int not null default 100
);

do $$
declare t text;
begin
  foreach t in array array['mc_revolut_tx', 'mc_revolut_sync', 'mc_revolut_rules'] loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists %I on %I', t || '_read', t);
    execute format('create policy %I on %I for select to authenticated using (owner = auth.uid())', t || '_read', t);
  end loop;
end $$;

-- Aggregates run as the caller (security invoker), so row-level security still applies.
-- Money that counts: not an own-pocket move, and not declined, failed or reverted.

create or replace function revolut_balances()
returns table (product text, balance numeric, as_of timestamp)
language sql stable security invoker set search_path = public as $$
  select distinct on (product) product, balance, started
  from mc_revolut_tx where balance is not null
  order by product, started desc, seq desc
$$;

create or replace function revolut_by_month(months int default 12)
returns table (month date, income numeric, spending numeric, net numeric, n int)
language sql stable security invoker set search_path = public as $$
  select date_trunc('month', day)::date,
         coalesce(sum(amount) filter (where amount > 0), 0),
         coalesce(-sum(amount) filter (where amount < 0), 0),
         sum(amount), count(*)::int
  from mc_revolut_tx
  where not internal and state in ('COMPLETED', 'PENDING')
    and day >= (date_trunc('month', current_date) - make_interval(months => greatest(months, 1) - 1))::date
  group by 1 order by 1 desc
$$;

create or replace function revolut_by_category(from_day date, to_day date)
returns table (category text, spending numeric, income numeric, n int)
language sql stable security invoker set search_path = public as $$
  select category,
         coalesce(-sum(amount) filter (where amount < 0), 0),
         coalesce(sum(amount) filter (where amount > 0), 0), count(*)::int
  from mc_revolut_tx
  where not internal and state in ('COMPLETED', 'PENDING') and day between from_day and to_day
  group by 1 order by 2 desc
$$;

create or replace function revolut_top_merchants(from_day date, to_day date, max_rows int default 15)
returns table (description text, spending numeric, n int)
language sql stable security invoker set search_path = public as $$
  select description, -sum(amount), count(*)::int
  from mc_revolut_tx
  where not internal and amount < 0 and state in ('COMPLETED', 'PENDING') and day between from_day and to_day
  group by 1 order by 2 desc limit least(greatest(max_rows, 1), 50)
$$;

grant execute on function revolut_balances(), revolut_by_month(int), revolut_by_category(date, date),
  revolut_top_merchants(date, date, int) to authenticated;
